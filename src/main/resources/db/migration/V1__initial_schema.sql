-- RippleMap schema v1. Snapshot rows (entities, edges, diagnostics, files) are written once, in the same
-- transaction that marks the analysis COMPLETED or PARTIAL, and never updated afterwards.

CREATE TABLE project (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(100)  NOT NULL,
    name_key         VARCHAR(100)  NOT NULL,
    description      VARCHAR(2000),
    source_type      VARCHAR(20)   NOT NULL,
    local_path       VARCHAR(1024),
    include_tests    BOOLEAN       NOT NULL,
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version          BIGINT        NOT NULL,
    CONSTRAINT uk_project_name_key UNIQUE (name_key)
);

CREATE TABLE source_import (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id        BIGINT        NOT NULL,
    version_number    INT           NOT NULL,
    original_filename VARCHAR(255),
    label             VARCHAR(100),
    archive_bytes     BIGINT        NOT NULL,
    archive_sha256    VARCHAR(64),
    entry_count       INT           NOT NULL,
    java_file_count   INT           NOT NULL,
    extracted_bytes   BIGINT        NOT NULL,
    storage_dir       VARCHAR(255)  NOT NULL,
    imported_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_import_project FOREIGN KEY (project_id) REFERENCES project (id) ON DELETE CASCADE,
    CONSTRAINT uk_import_version UNIQUE (project_id, version_number)
);

CREATE TABLE analysis (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id                  BIGINT        NOT NULL,
    source_import_id            BIGINT,
    sequence_number             INT           NOT NULL,
    status                      VARCHAR(20)   NOT NULL,
    trigger_type                VARCHAR(20)   NOT NULL,
    include_tests               BOOLEAN       NOT NULL,
    language_level              VARCHAR(20),
    analyzer_version            VARCHAR(20)   NOT NULL,
    created_at                  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    started_at                  TIMESTAMP(6) WITH TIME ZONE,
    finished_at                 TIMESTAMP(6) WITH TIME ZONE,
    duration_ms                 BIGINT,
    stage                       VARCHAR(200),
    error_message               VARCHAR(1000),
    partial_reasons             VARCHAR(1000),
    source_fingerprint          VARCHAR(64),
    files_discovered            INT,
    files_in_scope              INT,
    files_excluded_tests        INT,
    files_excluded_generated    INT,
    files_parsed                INT,
    files_failed                INT,
    files_skipped_links         INT,
    type_count                  INT,
    method_count                INT,
    constructor_count           INT,
    field_count                 INT,
    type_edge_count             INT,
    type_relationship_count     INT,
    method_edge_count           INT,
    method_relationship_count   INT,
    references_resolved         BIGINT,
    references_inferred         BIGINT,
    references_unresolved       BIGINT,
    references_likely_external  BIGINT,
    references_external         BIGINT,
    references_internal         BIGINT,
    solver_failures             BIGINT,
    info_count                  INT,
    warning_count               INT,
    error_count                 INT,
    diagnostics_stored          INT,
    diagnostics_truncated       BOOLEAN,
    type_cyclic_components      INT,
    type_nodes_in_cycles        INT,
    method_cyclic_components    INT,
    isolated_types              INT,
    node_metrics_computed       BOOLEAN,
    version                     BIGINT        NOT NULL,
    CONSTRAINT fk_analysis_project FOREIGN KEY (project_id) REFERENCES project (id) ON DELETE CASCADE,
    CONSTRAINT fk_analysis_import FOREIGN KEY (source_import_id) REFERENCES source_import (id) ON DELETE CASCADE,
    CONSTRAINT uk_analysis_sequence UNIQUE (project_id, sequence_number)
);
CREATE INDEX ix_analysis_project_status ON analysis (project_id, status);

CREATE TABLE code_entity (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_id             BIGINT        NOT NULL,
    stable_id               VARCHAR(2048) NOT NULL,
    kind                    VARCHAR(20)   NOT NULL,
    layer                   VARCHAR(10),
    name                    VARCHAR(512)  NOT NULL,
    qualified_name          VARCHAR(2048),
    package_name            VARCHAR(512),
    declaring_type_id       VARCHAR(2048),
    signature               VARCHAR(2048),
    file_path               VARCHAR(1024),
    line                    INT,
    end_line                INT,
    visibility              VARCHAR(20),
    modifiers               VARCHAR(200),
    test_source             BOOLEAN       NOT NULL,
    direct_dependencies     INT,
    direct_dependents       INT,
    transitive_dependents   INT,
    max_dependent_distance  INT,
    impact_score            DOUBLE PRECISION,
    in_cycle                BOOLEAN,
    CONSTRAINT fk_entity_analysis FOREIGN KEY (analysis_id) REFERENCES analysis (id) ON DELETE CASCADE
);
CREATE INDEX ix_entity_analysis_layer ON code_entity (analysis_id, layer);
CREATE UNIQUE INDEX uk_entity_stable_id ON code_entity (analysis_id, stable_id);

CREATE TABLE dependency_edge (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_id      BIGINT        NOT NULL,
    layer            VARCHAR(10)   NOT NULL,
    source_id        VARCHAR(2048) NOT NULL,
    target_id        VARCHAR(2048) NOT NULL,
    kind             VARCHAR(40)   NOT NULL,
    resolution       VARCHAR(20)   NOT NULL,
    reference_count  INT           NOT NULL,
    resolved_count   INT           NOT NULL,
    inferred_count   INT           NOT NULL,
    samples          CLOB,
    CONSTRAINT fk_edge_analysis FOREIGN KEY (analysis_id) REFERENCES analysis (id) ON DELETE CASCADE
);
CREATE INDEX ix_edge_analysis_layer ON dependency_edge (analysis_id, layer);

CREATE TABLE diagnostic (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_id  BIGINT        NOT NULL,
    severity     VARCHAR(10)   NOT NULL,
    category     VARCHAR(40)   NOT NULL,
    file_path    VARCHAR(1024),
    line         INT,
    entity_id    VARCHAR(2048),
    symbol       VARCHAR(256),
    message      VARCHAR(600)  NOT NULL,
    CONSTRAINT fk_diagnostic_analysis FOREIGN KEY (analysis_id) REFERENCES analysis (id) ON DELETE CASCADE
);
CREATE INDEX ix_diagnostic_analysis ON diagnostic (analysis_id, severity, category);

CREATE TABLE diagnostic_count (
    analysis_id  BIGINT      NOT NULL,
    category     VARCHAR(40) NOT NULL,
    item_count   INT         NOT NULL,
    PRIMARY KEY (analysis_id, category),
    CONSTRAINT fk_diagnostic_count_analysis FOREIGN KEY (analysis_id) REFERENCES analysis (id) ON DELETE CASCADE
);

CREATE TABLE source_file (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_id    BIGINT        NOT NULL,
    relative_path  VARCHAR(1024) NOT NULL,
    package_name   VARCHAR(512),
    sha256         VARCHAR(64),
    size_bytes     BIGINT        NOT NULL,
    line_count     INT           NOT NULL,
    status         VARCHAR(10)   NOT NULL,
    test_source    BOOLEAN       NOT NULL,
    type_count     INT           NOT NULL,
    CONSTRAINT fk_source_file_analysis FOREIGN KEY (analysis_id) REFERENCES analysis (id) ON DELETE CASCADE
);
CREATE INDEX ix_source_file_analysis ON source_file (analysis_id);

CREATE TABLE app_settings (
    id                   BIGINT       NOT NULL PRIMARY KEY,
    low_threshold        DECIMAL(6, 2) NOT NULL,
    high_threshold       DECIMAL(6, 2) NOT NULL,
    include_inferred     BOOLEAN      NOT NULL,
    explorer_node_limit  INT          NOT NULL,
    updated_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version              BIGINT       NOT NULL
);
INSERT INTO app_settings (id, low_threshold, high_threshold, include_inferred, explorer_node_limit, updated_at, version)
VALUES (1, 30.00, 60.00, TRUE, 300, CURRENT_TIMESTAMP, 0);
